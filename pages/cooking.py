import streamlit as st
from modules import recipes as rc, llm
from utils import history
from utils.ui import hero, badge

hero("🍳 Smart Cooking Assistant", "Tell us what is in your kitchen and get matching recipes.")
with st.form("cook"):
    text = st.text_area("Ingredients (comma separated)", placeholder="rice, onion, tomato, paneer")
    c1, c2, c3, c4 = st.columns(4)
    diet = c1.selectbox("Diet", ["Any", "Vegetarian", "Non-vegetarian"])
    cuisine = c2.multiselect("Cuisine", rc.cuisines())
    max_time = c3.slider("Max minutes", 10, 60, 45, 5)
    level = c4.selectbox("Difficulty", ["Any", "Easy", "Medium"])
    go = st.form_submit_button("Find recipes")

if go:
    have = rc.parse_ingredients(text)
    if not have:
        st.warning("Enter at least one ingredient.")
    else:
        found = rc.suggest(have, diet, cuisine, max_time, level)
        st.session_state["last_have"], st.session_state["last_diet"] = text, diet
        if not found:
            st.info("No library recipe matches those filters. Try more ingredients or relax the filters.")
        badge("rule")
        for r in found:
            with st.expander(f"{r['name']}  |  {r['cuisine']}  |  {r['time']} min  |  {r['difficulty']}  |  {r['score']:.0%} of ingredients on hand"):
                st.markdown(("🥦 Vegetarian" if r["veg"] else "🍗 Contains meat or egg"))
                st.markdown("**Ingredients**\n" + "\n".join(f"- {n}: {q}" + ("" if n in r["missing"] else " ✅") for n, q in r["ingredients"]))
                if r["missing"]:
                    st.caption("Missing: " + ", ".join(r["missing"]))
                st.markdown("**Steps**\n" + "\n".join(f"{i}. {s}" for i, s in enumerate(r["steps"], 1)))
                if r["subs"]:
                    st.markdown("**Substitutions:** " + "; ".join(f"{k} → {v}" for k, v in r["subs"].items()))
                if st.button("Save to history", key="sv" + r["name"]):
                    history.add("Cooking", r["name"], r["cuisine"], None, "recipe library")
                    st.success("Saved.")

st.subheader("Custom recipe with an LLM (optional)")
if llm.is_configured():
    ask = st.text_input("Describe what you want", placeholder="High-protein dinner in 20 minutes using the ingredients above")
    if st.button("Generate with LLM") and ask:
        prompt = (f"Ingredients available: {st.session_state.get('last_have', 'unspecified')}. "
                  f"Diet: {st.session_state.get('last_diet', 'Any')}. Request: {ask}")
        with st.spinner("Asking the LLM..."):
            out, err = llm.ask(prompt)
        if err:
            st.error(err)
        else:
            st.caption("Generated by an LLM; check quantities and safe cooking temperatures.")
            st.markdown(out)
else:
    st.info("No `ANTHROPIC_API_KEY` is configured, so LLM recipes are off. The recipe library above works without it. "
            "To enable it, see the README (Configuration).")
